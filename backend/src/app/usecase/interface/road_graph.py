from typing import Any, Protocol

from app.domain.road_economics import MoneyAssumptions
from app.usecase.dto.road_graph import (
    DeltaRegion,
    GraphLocation,
    RoadAddition,
    RoadChange,
    RoadJob,
    RoadView,
)


class RoadGraphPort(Protocol):
    def locations(self, query: str, region_id: str | None) -> list[GraphLocation]: ...
    def view(self, bounds: tuple[float, float, float, float], zoom: float) -> RoadView: ...
    def submit(
        self, region_id: str, region: str, scenario: str, changes: list[RoadChange]
    ) -> RoadJob: ...
    def submit_addition(
        self, region_id: str, region: str, addition: RoadAddition, money: MoneyAssumptions | None
    ) -> RoadJob: ...
    def recent(self) -> list[RoadJob]: ...
    def job(self, job_id: str) -> RoadJob: ...
    def cancel(self, job_id: str) -> RoadJob: ...


class RoadViewSource(Protocol):
    def view(self, bounds: tuple[float, float, float, float], zoom: float) -> RoadView: ...


class RoadJobStore(Protocol):
    def load(self) -> dict[str, RoadJob]: ...
    def save(self, job: RoadJob) -> None: ...


class BaselineStore(Protocol):
    def key(self, region: str, scenario: str) -> str: ...
    def read(self, region: str, scenario: str) -> float | None: ...
    def write(self, region: str, scenario: str, value: float) -> None: ...


class DeltaRegionStore(Protocol):
    def names(self) -> list[str]: ...
    def read(self, region: str) -> DeltaRegion | None: ...
    def write(self, region: str, value: DeltaRegion) -> None: ...
    def read_terminal(self, node: int) -> tuple[Any, Any] | None: ...
    def write_terminal(self, node: int, nodes: Any, distances: Any) -> None: ...
    def write_manifest(self, report: dict[str, object]) -> None: ...


class GraphMatrixStore(Protocol):
    def read(self) -> Any | None: ...
    def write(self, graph: Any) -> None: ...
